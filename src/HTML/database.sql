CREATE DATABASE IF NOT EXISTS esp32_mesh;
USE esp32_mesh;

CREATE TABLE IF NOT EXISTS rssi_readings (
  id INT AUTO_INCREMENT PRIMARY KEY,
  ssid VARCHAR(128) NOT NULL,
  rssi INT NOT NULL,
  sec VARCHAR(32) DEFAULT NULL,
  mac VARCHAR(17) NOT NULL,
  reading_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  node_id VARCHAR(50) DEFAULT NULL,
  INDEX (mac),
  INDEX (ssid),
  INDEX (reading_time)
);